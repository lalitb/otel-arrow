//! Checked-in golden/conformance byte vectors for the version-1 filelog
//! checkpoint codec.
//!
//! Every vector here was assembled independently of this crate's own
//! encoder: field-by-field, against `docs/filelog-checkpoint-format.md`,
//! using a separate Python reference script whose CRC-32C came from an
//! independently implemented bit-by-bit Castagnoli algorithm (matching the
//! published `CRC-32C("123456789") = 0xE3069283` check value) and whose
//! SHA-256 came from the Python standard library. This guards against a
//! matched bug in this crate's encoder and decoder hiding a specification
//! violation that a pure round-trip test would miss.
//!
