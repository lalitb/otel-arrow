//! Every vector here was assembled independently of this crate's own
//! encoder: field-by-field, against `docs/filelog-checkpoint-format.md`,
//! using a separate reference script whose CRC-32C came from an
//! independently verified bit-by-bit Castagnoli implementation (matching
//! the published `CRC-32C("123456789") = 0xE3069283` check value) and whose
